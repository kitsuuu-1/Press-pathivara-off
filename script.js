function applyTheme(th) {
  document.documentElement.setAttribute('data-theme', th);
  themeBtn.textContent = th === 'dark' ? '☀️' : '🌙';
}
let saved = null;
try { saved = localStorage.getItem('theme'); } catch (e) {}
applyTheme(saved || 'light');
themeBtn.addEventListener('click', () => {
  const next = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
  applyTheme(next);
  try { localStorage.setItem('theme', next); } catch (e) {}
});

// Scroll reveal
const io = new IntersectionObserver((entries) => {
  entries.forEach(e => { if (e.isIntersecting) { e.target.classList.add('visible'); io.unobserve(e.target); } });
}, { threshold: .15 });
document.querySelectorAll('.reveal').forEach(el => io.observe(el));

// Quote form -> opens WhatsApp with a prefilled message
document.getElementById('quoteForm').addEventListener('submit', (e) => {
  e.preventDefault();
  const name = document.getElementById('name').value.trim();
  const phone = document.getElementById('phone').value.trim();
  const service = document.getElementById('service').value;
  const qty = document.getElementById('qty').value.trim();
  const details = document.getElementById('message').value.trim();
  const out = document.getElementById('formMsg');

  if (!name || !phone) { out.className = 'msg error'; out.textContent = t('Please enter your name and phone number.'); return; }

  const text = [
    'Hello Press Pathivara,',
    `Name: ${name}`,
    `Phone: ${phone}`,
    `Service: ${service}`,
    qty && `Quantity: ${qty}`,
    details && `Details: ${details}`
  ].filter(Boolean).join('\n');

  window.open(`https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(text)}`, '_blank');
  out.className = 'msg ok';
  out.textContent = t('Opening WhatsApp with your request...');
});

