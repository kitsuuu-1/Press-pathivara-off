let lang = 'en';
const t = (s) => (lang === 'ne' && NE[s]) || s;

// Look up text; allow a leading emoji (e.g. "📍 Address")
function lookup(key) {
  if (NE[key]) return NE[key];
  const m = key.match(/^(\S+)\s+([\s\S]+)$/);
  return m && NE[m[2]] ? m[1] + ' ' + NE[m[2]] : null;
}

// Collect every translatable text node and placeholder once
const items = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const n = walker.currentNode;
  if (n.parentNode.closest('script, #langModal, #langBtn, #themeBtn, #menuBtn')) continue;
  const key = n.nodeValue.trim();
  if (key && lookup(key)) {
    items.push({ node: n, key, lead: n.nodeValue.match(/^\s*/)[0], trail: n.nodeValue.match(/\s*$/)[0] });
  }
}
const placeholders = [...document.querySelectorAll('[placeholder]')].map(el => ({ el, key: el.getAttribute('placeholder') }));
const titleKey = document.title;

function setLang(l) {
  lang = l;
  document.documentElement.lang = l === 'ne' ? 'ne' : 'en';
  items.forEach(i => { i.node.nodeValue = i.lead + (l === 'ne' ? lookup(i.key) : i.key) + i.trail; });
  placeholders.forEach(p => p.el.setAttribute('placeholder', l === 'ne' ? (NE[p.key] || p.key) : p.key));
  document.title = l === 'ne' ? NE[titleKey] || titleKey : titleKey;
  langBtn.textContent = l === 'ne' ? 'EN' : 'नेपाली';
  const out = document.getElementById('formMsg');
  out.textContent = '';
}

/* ---------- Language popup ---------- */
const langModal = document.getElementById('langModal');
const langBtn = document.getElementById('langBtn');
function openModal() { langModal.hidden = false; document.body.style.overflow = 'hidden'; }
function chooseLang(l) {
  setLang(l);
  try { localStorage.setItem('lang', l); } catch (e) {}
  langModal.hidden = true;
  document.body.style.overflow = '';
}
langModal.querySelectorAll('[data-lang]').forEach(b => b.addEventListener('click', () => chooseLang(b.dataset.lang)));
langBtn.addEventListener('click', () => { setLang(lang === 'ne' ? 'en' : 'ne'); try { localStorage.setItem('lang', lang); } catch (e) {} });

let savedLang = null;
try { savedLang = localStorage.getItem('lang'); } catch (e) {}
if (savedLang === 'ne' || savedLang === 'en') setLang(savedLang);
else openModal(); // first visit: ask which language

